const chunk = (type, data) => {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(zlib.crc32(td) >>> 0);
  return Buffer.concat([len, td, crc]);
};

function hsl(h, s, l) {
  const a = s * Math.min(l, 1 - l);
  const f = (n) => {
    const k = (n + h / 30) % 12;
    return Math.round(255 * (l - a * Math.max(-1, Math.min(k - 3, 9 - k, 1))));
  };
  return [f(0), f(8), f(4)];
}

export function icon(letters, seed = letters, hue) {
  const W = 128;
  let h = 0;
  for (const c of seed) h = (h * 31 + c.charCodeAt(0)) >>> 0;
  const hu = hue ?? h % 360;
  const c1 = hsl(hu, 0.65, 0.52);
  const c2 = hsl((hu + 40) % 360, 0.7, 0.36);
  const text = letters.toUpperCase().replace(/[^A-Z0-9+#.\-*]/g, '').slice(0, 3) || '?';
  const n = text.length;
  const s = n === 1 ? 12 : n === 2 ? 9 : 5;
  const tw = n * 5 * s + (n - 1) * s;
  const x0 = Math.round((W - tw) / 2);
  const y0 = Math.round((W - 7 * s) / 2);
  const px = Buffer.alloc(W * W * 4);
  const R = 22;
  for (let y = 0; y < W; y++) {
    for (let x = 0; x < W; x++) {
      const t = (x + y) / (2 * (W - 1));
      let r = c1[0] + (c2[0] - c1[0]) * t, g = c1[1] + (c2[1] - c1[1]) * t, b = c1[2] + (c2[2] - c1[2]) * t, a = 255;
      const dx = Math.max(R - x, x - (W - 1 - R), 0), dy = Math.max(R - y, y - (W - 1 - R), 0);
      if (dx * dx + dy * dy > R * R) a = 0;
      const gx = x - x0, gy = y - y0;
      if (gx >= 0 && gy >= 0 && gy < 7 * s && gx < tw) {
        const ci = Math.floor(gx / (6 * s)), cx = gx - ci * 6 * s;
        if (ci < n && cx < 5 * s) {
          const rows = (F[text[ci]] ?? F['-']).split('|');
          if (rows[Math.floor(gy / s)][Math.floor(cx / s)] === '#') { r = 255; g = 255; b = 255; }
        }
      }
      const o = (y * W + x) * 4;
      px[o] = r; px[o + 1] = g; px[o + 2] = b; px[o + 3] = a;
    }
  }
  const raw = Buffer.alloc((W * 4 + 1) * W);
  for (let y = 0; y < W; y++) { raw[y * (W * 4 + 1)] = 0; px.copy(raw, y * (W * 4 + 1) + 1, y * W * 4, (y + 1) * W * 4); }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(W, 0); ihdr.writeUInt32BE(W, 4); ihdr[8] = 8; ihdr[9] = 6;
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(raw, { level: 9 })), chunk('IEND', Buffer.alloc(0))]);
}
